/**
 * 重量记录规范 —— 单一事实来源
 *
 * 同一个动作到底记多少 kg, 在健身记录里是出了名的歧义点:
 * 杠铃含不含杆? 哑铃记单只还是双只? 器械挂片左右要不要相加?
 * 记法不一致会让 1RM 估算与训练容量统计出现系统性偏差, 趋势图也会断层。
 *
 * 本文件被三处引用, 保证口径完全一致:
 *   1. lib/ai/analyze.ts        —— AI 分析时告知口径, 避免误判为力量退步
 *   2. lib/utils/export-bundle.ts —— 导出包的数据字典, 供外部工具/AI 正确解读
 *   3. 记录表单的输入提示        —— 录入时就按规范填
 */

/** 判断原则: 一句话覆盖所有器械, 不必逐个记忆 */
export const WEIGHT_RULE = "负荷汇聚到同一条运动轨迹 → 记总和；左右各走各的 → 记单侧";

/** 表单里的一行短提示 */
export const WEIGHT_HINT = "杠铃含杆重，哑铃记单只";

/** 完整规范 (喂给 AI / 写进数据字典) */
export const WEIGHT_CONVENTION = `重量(weight_kg)记录口径 —— 判断原则：${WEIGHT_RULE}

- 杠铃动作：杆重 + 全部杠铃片。标准奥杆 20kg，短杆/女杆 15kg。
  例：杆 20 + 左右各 10kg = 40kg
- 哑铃动作：记单只重量。例：双手各持 22.5kg，记 22.5 而非 45
- 插销式配重器械 / 龙门架 / 绳索：记配重片标示数字
- 挂片式联动器械（左右连在一起动）：两侧片重相加
- 挂片式独立臂器械（左右分开各推各的，如悍马机）：记单侧重量
- 自重 + 负重动作（引体、双杠臂屈伸）：只记额外负重，体重见 daily_metrics`;

/** 解读数据时的注意事项 */
export const WEIGHT_CAVEATS = `解读注意：
- 哑铃与独立臂器械记的是单侧重量，双侧同时进行的动作，其训练容量应按两倍理解
- 器械存在杠杆比，标示重量不等于身体实际承受的负荷，只适合同一台器械纵向对比，
  不宜与杠铃动作或别的器械横向比较
- Epley 1RM 估算对杠铃动作最有参考价值；器械与哑铃动作的 1RM 仅供纵向参考
- 若某动作重量出现突变，先考虑是否换了器械或记法，再判断是否为力量变化`;
