-- ============================================================================
-- 0003 饮食记录支持「全天」餐次
--
-- 原来只能按 早/午/晚/加餐 分别录入。实际用起来更常见的是一次把一整天吃的
-- 都写下来, 交给 AI 一次估算总量, 所以加一个 all_day。
-- ============================================================================

alter table public.meal_logs
  drop constraint if exists meal_logs_meal_type_check;

alter table public.meal_logs
  add constraint meal_logs_meal_type_check
  check (meal_type in ('all_day','breakfast','lunch','dinner','snack'));

